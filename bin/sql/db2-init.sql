CREATE TABLE CONTACTS (
    CONTACT_ID BIGINT NOT NULL PRIMARY KEY,
    DISPLAY_NAME VARCHAR(512),
    DATE_OF_BIRTH VARCHAR(128),
    PREFERRED_LANGUAGE VARCHAR(10) NOT NULL,
    CONTACT_STATUS VARCHAR(16) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT CONTACTS_STATUS_CK CHECK (CONTACT_STATUS IN ('ACTIVE', 'ARCHIVED', 'PENDING'))
);
INSERT INTO CONTACTS
SELECT ID, 'Contact ' || VARCHAR(ID),
       VARCHAR(DATE('1980-01-01') + MOD(ID, 15000) DAYS),
       CASE MOD(ID, 3) WHEN 0 THEN 'fr-CA' WHEN 1 THEN 'en-US' ELSE 'es-MX' END,
       CASE WHEN MOD(ID, 20) = 0 THEN 'PENDING'
            WHEN MOD(ID, 10) = 0 THEN 'ARCHIVED' ELSE 'ACTIVE' END,
       TIMESTAMP('2020-01-01 00:00:00') + MOD(ID, 200000000) SECONDS,
       TIMESTAMP('2020-01-01 00:00:00') + MOD(ID, 200000000) SECONDS
FROM SESSION.ADDRESS_BOOK_NUMBERS;
COMMIT;

CREATE TABLE CONTACT_ADDRESSES (
    ADDRESS_ID BIGINT NOT NULL PRIMARY KEY,
    CONTACT_ID BIGINT NOT NULL REFERENCES CONTACTS(CONTACT_ID),
    ADDRESS_TYPE VARCHAR(16) NOT NULL,
    STREET VARCHAR(512),
    LOCALITY VARCHAR(256),
    POSTAL_CODE VARCHAR(128),
    COUNTRY_CODE CHAR(2) NOT NULL,
    IS_PRIMARY SMALLINT NOT NULL,
    VALID_FROM DATE NOT NULL,
    VALID_TO DATE,
    CONSTRAINT CONTACT_ADDRESSES_TYPE_CK CHECK (ADDRESS_TYPE IN ('HOME', 'WORK', 'OTHER')),
    CONSTRAINT CONTACT_ADDRESSES_DATE_CK CHECK (VALID_TO IS NULL OR VALID_TO >= VALID_FROM),
    CONSTRAINT CONTACT_ADDRESSES_PRIMARY_CK CHECK (IS_PRIMARY IN (0, 1))
);
INSERT INTO CONTACT_ADDRESSES
SELECT ID, ID,
       CASE MOD(ID, 3) WHEN 0 THEN 'WORK' WHEN 1 THEN 'HOME' ELSE 'OTHER' END,
       'Street ' || VARCHAR(ID),
       'City ' || VARCHAR(MOD(ID, 100000)),
       'T' || RIGHT('00000' || VARCHAR(MOD(ID, 100000)), 5),
       CASE MOD(ID, 4) WHEN 0 THEN 'CA' WHEN 1 THEN 'US' WHEN 2 THEN 'FR' ELSE 'GB' END,
       1, DATE('2018-01-01') + MOD(ID, 2500) DAYS, NULL
FROM SESSION.ADDRESS_BOOK_NUMBERS;
COMMIT;

CREATE TABLE CONTACT_PHONES (
    PHONE_ID BIGINT NOT NULL PRIMARY KEY,
    CONTACT_ID BIGINT NOT NULL REFERENCES CONTACTS(CONTACT_ID),
    PHONE_TYPE VARCHAR(16) NOT NULL,
    PHONE_NUMBER VARCHAR(256),
    EXTENSION VARCHAR(128),
    IS_PRIMARY SMALLINT NOT NULL,
    VERIFIED_AT TIMESTAMP,
    CONSTRAINT CONTACT_PHONES_TYPE_CK CHECK (PHONE_TYPE IN ('MOBILE', 'HOME', 'WORK', 'OTHER')),
    CONSTRAINT CONTACT_PHONES_PRIMARY_CK CHECK (IS_PRIMARY IN (0, 1))
);
INSERT INTO CONTACT_PHONES
SELECT ID, ID,
       CASE MOD(ID, 4) WHEN 0 THEN 'WORK' WHEN 1 THEN 'MOBILE'
                       WHEN 2 THEN 'HOME' ELSE 'OTHER' END,
       '+1-555-010-' || RIGHT('0000' || VARCHAR(MOD(ID, 10000)), 4),
       RIGHT('000' || VARCHAR(MOD(ID, 1000)), 3), 1,
       CASE WHEN MOD(ID, 5) = 0 THEN NULL
            ELSE TIMESTAMP('2022-01-01 00:00:00') + MOD(ID, 100000000) SECONDS
       END
FROM SESSION.ADDRESS_BOOK_NUMBERS;
COMMIT;

CREATE TABLE CONTACT_EMAILS (
    EMAIL_ID BIGINT NOT NULL PRIMARY KEY,
    CONTACT_ID BIGINT NOT NULL REFERENCES CONTACTS(CONTACT_ID),
    EMAIL_TYPE VARCHAR(16) NOT NULL,
    EMAIL_ADDRESS VARCHAR(512),
    IS_PRIMARY SMALLINT NOT NULL,
    IS_VERIFIED SMALLINT NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT CONTACT_EMAILS_TYPE_CK CHECK (EMAIL_TYPE IN ('PERSONAL', 'WORK', 'OTHER')),
    CONSTRAINT CONTACT_EMAILS_PRIMARY_CK CHECK (IS_PRIMARY IN (0, 1)),
    CONSTRAINT CONTACT_EMAILS_VERIFIED_CK CHECK (IS_VERIFIED IN (0, 1))
);
INSERT INTO CONTACT_EMAILS
SELECT ID, ID,
       CASE MOD(ID, 3) WHEN 0 THEN 'WORK' WHEN 1 THEN 'PERSONAL' ELSE 'OTHER' END,
       'contact' || VARCHAR(ID) || '@example.test', 1,
       CASE WHEN MOD(ID, 5) = 0 THEN 0 ELSE 1 END,
       TIMESTAMP('2021-01-01 00:00:00') + MOD(ID, 150000000) SECONDS
FROM SESSION.ADDRESS_BOOK_NUMBERS;
COMMIT;

CREATE TABLE CONTACT_RELATIONSHIPS (
    RELATIONSHIP_ID BIGINT NOT NULL PRIMARY KEY,
    CONTACT_ID BIGINT NOT NULL REFERENCES CONTACTS(CONTACT_ID),
    RELATED_CONTACT_ID BIGINT NOT NULL REFERENCES CONTACTS(CONTACT_ID),
    RELATIONSHIP_TYPE VARCHAR(16) NOT NULL,
    NOTES VARCHAR(2048),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT CONTACT_RELATIONSHIPS_NOT_SELF_CK CHECK (CONTACT_ID <> RELATED_CONTACT_ID),
    CONSTRAINT CONTACT_RELATIONSHIPS_TYPE_CK
        CHECK (RELATIONSHIP_TYPE IN ('FAMILY', 'FRIEND', 'COLLEAGUE', 'OTHER')),
    CONSTRAINT CONTACT_RELATIONSHIPS_PAIR_UQ UNIQUE (CONTACT_ID, RELATED_CONTACT_ID)
);
INSERT INTO CONTACT_RELATIONSHIPS
SELECT ID, ID, CASE WHEN ID = 10000000 THEN 1 ELSE ID + 1 END,
       CASE MOD(ID, 4) WHEN 0 THEN 'COLLEAGUE' WHEN 1 THEN 'FAMILY'
                       WHEN 2 THEN 'FRIEND' ELSE 'OTHER' END,
       'Synthetic relationship note ' || VARCHAR(ID),
       TIMESTAMP('2023-01-01 00:00:00') + MOD(ID, 50000000) SECONDS
FROM SESSION.ADDRESS_BOOK_NUMBERS;
COMMIT;

CREATE INDEX CONTACT_ADDRESSES_CONTACT_IDX ON CONTACT_ADDRESSES(CONTACT_ID);
