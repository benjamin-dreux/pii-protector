CREATE INDEX CONTACT_EMAILS_CONTACT_IDX ON CONTACT_EMAILS(CONTACT_ID);
CREATE INDEX CONTACT_RELATIONSHIPS_RELATED_IDX ON CONTACT_RELATIONSHIPS(RELATED_CONTACT_ID);
